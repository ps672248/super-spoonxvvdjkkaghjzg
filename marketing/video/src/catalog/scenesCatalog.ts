/**
 * Aspirant Arcade 100+ Shot & Scene Catalog.
 *
 * Provides a modular library of 100+ reusable character poses, emotional states,
 * product gameplay views, and celebratory endings for Arjun and Priya.
 *
 * Each shot contains:
 * - id: unique semantic identifier
 * - category: 'hooks_and_struggles' | 'mentor_interventions' | 'gameplay_and_product' | 'breakthrough_and_cta'
 * - character: 'arjun' | 'priya' | 'both' | 'screen'
 * - mood: emotional tone of the character
 * - setting: environment setting
 * - camera: camera framing
 * - description: rich semantic description for the Gemini Director
 * - tags: searchable keywords for story matching
 * - assetPath: dedicated asset path in public/
 * - fallbackAsset: high-res existing fallback in public/scenes/
 * - mouth: optional facial coordinates for procedural lip-sync
 */

export interface MouthAnchor {
  centerX: string;
  centerY: string;
  baseWidth: number;
  maxHeight: number;
  rotationDeg: number;
  lipColor: string;
}

