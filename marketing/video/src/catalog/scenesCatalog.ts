/** Helper to retrieve a shot with safe fallback */
export function getShotDefinition(sceneId: string): ShotDefinition {
  if (SCENES_CATALOG[sceneId]) {
    return SCENES_CATALOG[sceneId];
  }
  // Fallback to arjun_head_in_hands_books if ID is unknown
  return SCENES_CATALOG['arjun_head_in_hands_books'];
}

/** Summarized catalog prompt for Gemini Film Director */
export function buildCatalogPromptSummary(): string {
  const categories: Record<string, string[]> = {
    hooks_and_struggles: [],
    mentor_interventions: [],
    gameplay_and_product: [],
    breakthrough_and_cta: [],
  };

  for (const shot of Object.values(SCENES_CATALOG)) {
    categories[shot.category].push(`- "${shot.id}" (${shot.character}, ${shot.mood}): ${shot.description}`);
  }

  return `
=== ASPIRANT ARCADE 100+ SHOT CATALOG ===

[1. HOOKS & STRUGGLES (Arjun Pain Points)]
${categories.hooks_and_struggles.join('\n')}

[2. MENTOR INTERVENTIONS (Priya Challenging & Guiding)]
${categories.mentor_interventions.join('\n')}

[3. GAMEPLAY & PRODUCT (Aspirant Arcade Features)]
${categories.gameplay_and_product.join('\n')}

[4. BREAKTHROUGH & CTA (Celebrations & Downloads)]
${categories.breakthrough_and_cta.join('\n')}
`;
}
